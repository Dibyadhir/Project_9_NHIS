"""Streamlit interface for the Equity Research News Tool."""

import logging

import streamlit as st

from langchain_config import (
    NewsToolError,
    NoArticlesError,
    ResearchResult,
    fetch_articles,
    generate_final_summary,
    summarize_articles,
)

logger = logging.getLogger(__name__)

st.set_page_config(
    page_title="Equity Research News Tool",
    page_icon="📈",
    layout="centered",
)


# ---------------------------------------------------------------------------
# Cached helpers: the same search within 15 minutes reuses earlier results,
# which protects the free NewsAPI and Gemini limits. Errors are never cached.
# ---------------------------------------------------------------------------
@st.cache_data(ttl=900, show_spinner=False)
def load_articles(query: str):
    return fetch_articles(query)


@st.cache_data(ttl=900, show_spinner=False)
def load_summary(query: str, digest: str) -> str:
    return generate_final_summary(query, digest)


def run_research(query: str) -> ResearchResult:
    """Query -> NewsAPI -> clean articles -> Gemini summary."""
    articles = load_articles(query)  # raises NewsToolError if nothing usable
    digest = summarize_articles(articles)

    if not digest:
        return ResearchResult(
            query=query,
            articles=articles,
            summary=None,
            warning=(
                "Articles were found, but none included a description or text, "
                "so no AI summary was generated."
            ),
        )

    try:
        summary = load_summary(query, digest)
    except NewsToolError as error:
        # Keep the articles visible even if the AI step fails.
        return ResearchResult(
            query=query,
            articles=articles,
            summary=None,
            warning=f"The articles were retrieved, but the AI summary failed. {error}",
        )

    return ResearchResult(query=query, articles=articles, summary=summary)


# ---------------------------------------------------------------------------
# Display helpers
# ---------------------------------------------------------------------------
def escape_dollars(text: str) -> str:
    """Streamlit treats text between two $ signs as math, which garbles prices."""
    return text.replace("$", "\\$")


def render_summary(result: ResearchResult) -> None:
    st.subheader("AI-Generated Summary")
    if result.summary:
        st.markdown(escape_dollars(result.summary))
        st.caption(
            "Generated by Gemini from the article text listed below. "
            "Numbers like [1] refer to those articles. Verify details in the originals."
        )
    elif result.warning:
        st.warning(result.warning)


def render_articles(result: ResearchResult) -> None:
    articles = result.articles
    sources = {article.source for article in articles}
    st.subheader(f"News Articles ({len(articles)})")
    st.caption(f"{len(articles)} articles from {len(sources)} sources")

    for number, article in enumerate(articles, start=1):
        with st.container(border=True):
            st.markdown(f"**[{number}] {escape_dollars(article.title)}**")
            st.caption(f"{article.source} · {article.published_at}")
            if article.has_text:
                st.write(escape_dollars(article.text))
            else:
                st.caption("No description is available for this article.")
            st.link_button("Read original article", article.url)


# ---------------------------------------------------------------------------
# Page layout
# ---------------------------------------------------------------------------
with st.sidebar:
    st.header("About")
    st.write(
        "This tool fetches recent news with NewsAPI and uses LangChain with "
        "Google Gemini to summarize it for equity research."
    )
    st.subheader("Try these searches")
    st.markdown(
        "- Tesla stock news\n"
        "- Apple financial news\n"
        "- NVIDIA AI market news\n"
        "- Reliance Industries stock news"
    )
    st.caption(
        "NewsAPI's free plan delays articles by about 24 hours and allows "
        "about 100 requests per day."
    )
    st.caption("For research only. This is not financial advice.")

st.title("Equity Research News Tool")
st.write(
    "Enter a company name, stock ticker or financial topic to get recent news "
    "articles and an AI-generated summary."
)

with st.form("search_form"):
    query = st.text_input(
        "Company, ticker or topic",
        placeholder="e.g. Tesla stock news",
    )
    submitted = st.form_submit_button("Get News", type="primary")

if submitted:
    cleaned_query = query.strip()

    if not cleaned_query:
        st.warning("Please enter a company name, ticker or topic.")
    else:
        try:
            with st.spinner("Fetching news and generating the summary..."):
                research = run_research(cleaned_query)
        except NoArticlesError as error:
            st.info(str(error))
        except NewsToolError as error:
            st.error(str(error))
        except Exception:
            logger.exception("Unexpected error while running the search")
            st.error(
                "Something unexpected went wrong. Please try again, and check "
                "the terminal window for details."
            )
        else:
            render_summary(research)
            render_articles(research)